import base64
import hashlib
import re
import struct
import subprocess

import pytest
from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa

# See the HAB4 API Reference Manual and the CST User's Guide
HAB_TAG_CSF = 0xd4
HAB_TAG_CRT = 0xd7
HAB_TAG_SIG = 0xd8
HAB_CMD_INS_KEY = 0xbe
HAB_CMD_AUT_DAT = 0xca
HAB_PCL_SRK = 0x03
HAB_PCL_X509 = 0x09
HAB_PCL_CMS = 0xc5

PAYLOAD_SIZE = 0x1000
LOAD_ADDRESS = 0x80000000

# Paths are filled in by the server, the file names come from the PKI tree
# generated by imx.generate_hab.
CSF = f"""[Header]
    Version = 4.3
    Hash Algorithm = sha256
    Engine = ANY
    Engine Configuration = 0
    Certificate Format = X509
    Signature Format = CMS

[Install SRK]
    File = "%%CERTS_PATH%%/../SRK_table.bin"
    Source index = 0

[Install CSFK]
    File = "%%CERTS_PATH%%/CSF1_1_sha256_4096_65537_v3_usr_crt.pem"

[Authenticate CSF]

[Install Key]
    Verification index = 0
    Target index = 2
    File = "%%CERTS_PATH%%/IMG1_1_sha256_4096_65537_v3_usr_crt.pem"

[Authenticate Data]
    Verification index = 2
    Blocks = {LOAD_ADDRESS:#x} 0x0 {PAYLOAD_SIZE:#x} "%%BIN_PATH%%"
"""


def hab_header(data, offset):
    return struct.unpack(">BHB", data[offset:offset + 4])


def hab_blob(data, offset, tag):
    blob_tag, length, _ = hab_header(data, offset)
    assert blob_tag == tag
    return data[offset:offset + length]


def parse_csf(csf):
    """
    Returns the SRK table, installed certificates by their key index and
    signatures as (key index, blocks, signature) found in a CSF binary.
    """
    tag, length, _ = hab_header(csf, 0)
    assert tag == HAB_TAG_CSF

    srk_table = None
    certs = {}
    signatures = []
    offset = 4
    while offset < length:
        tag, cmd_length, _ = hab_header(csf, offset)
        cmd = csf[offset:offset + cmd_length]
        if tag == HAB_CMD_INS_KEY:
            _, protocol, _, _, target, data = struct.unpack(">BBBBBI", cmd[3:12])
            blob = hab_blob(csf, data, HAB_TAG_CRT)
            if protocol == HAB_PCL_SRK:
                srk_table = blob
            else:
                assert protocol == HAB_PCL_X509
                certs[target] = x509.load_der_x509_certificate(blob[4:])
        elif tag == HAB_CMD_AUT_DAT:
            _, key, protocol, _, _, data = struct.unpack(">BBBBBI", cmd[3:12])
            assert protocol == HAB_PCL_CMS
            blocks = [struct.unpack(">II", cmd[i:i + 8])
                      for i in range(12, cmd_length, 8)]
            signature = hab_blob(csf, data, HAB_TAG_SIG)[4:]
            signatures.append((key, blocks, signature))
        offset += cmd_length

    return csf[:length], srk_table, certs, signatures


def parse_srk_table(table):
    keys = []
    offset = 4
    while offset < len(table):
        _, length, _ = hab_header(table, offset)
        keys.append(table[offset:offset + length])
        offset += length
    return keys


def srk_public_key(key):
    modulus_length, exponent_length = struct.unpack(">HH", key[8:12])
    modulus = key[12:12 + modulus_length]
    exponent = key[12 + modulus_length:12 + modulus_length + exponent_length]
    return rsa.RSAPublicNumbers(int.from_bytes(exponent, "big"),
                                int.from_bytes(modulus, "big")).public_key()


def srk_efuses(keys):
    # HAB4 fuses the hash of the concatenated hashes of the SRKs
    return hashlib.sha256(
        b"".join(hashlib.sha256(key).digest() for key in keys)).digest()


def issued_by(cert, public_key):
    try:
        public_key.verify(cert.signature, cert.tbs_certificate_bytes,
                          padding.PKCS1v15(), cert.signature_hash_algorithm)
    except Exception:
        return False
    return True


def verify_cms(tmp_path, cert, content, signature):
    cert_path = tmp_path / "cert.pem"
    content_path = tmp_path / "content"
    signature_path = tmp_path / "signature.der"
    cert_path.write_bytes(cert.public_bytes(serialization.Encoding.PEM))
    content_path.write_bytes(content)
    signature_path.write_bytes(signature)

    # The chain to the SRK isn't X.509, it's checked separately
    cmd = [
        "openssl", "cms", "-verify", "-noverify", "-binary", "-inform", "DER",
        "-in", str(signature_path), "-content", str(content_path),
        "-certfile", str(cert_path), "-out", "/dev/null",
    ]
    return subprocess.run(cmd, capture_output=True).returncode == 0


def create_pki(client, hab_type):
    response = client.post("/imx/pki", json={"hab_type": hab_type})
    assert response.status_code == 200
    return response.json()["pki_id"]


def get_efuses(client, pki_id):
    response = client.get(f"/imx/efuses/{pki_id}")
    assert response.status_code == 200
    return base64.b64decode(response.json()["efuses"])


def sign(client, pki_id, payload):
    response = client.post("/imx/cst", json={
        "pki_id": pki_id,
        "hab_type": "hab",
        "csf": base64.b64encode(CSF.encode()).decode(),
        "payload": base64.b64encode(payload).decode(),
    })
    assert response.status_code == 200
    return base64.b64decode(response.json()["csf_bin"])


