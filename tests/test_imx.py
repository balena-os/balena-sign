@pytest.mark.parametrize("pki", ["hab_pki", "ahab_pki"])
def test_new(anonymous_client, request, pki):
    pki_id = request.getfixturevalue(pki)
    assert re.fullmatch("[0-9a-f]{32}", pki_id)

    response = anonymous_client.get("/imx/pkis")
    assert response.status_code == 200
    assert pki_id in response.json()["pkis"]


def test_pkis_unique(hab_pki, ahab_pki):
    assert hab_pki != ahab_pki


def test_efuses_hab(anonymous_client, hab_pki):
    assert len(get_efuses(anonymous_client, hab_pki)) == hashlib.sha256().digest_size


def test_efuses_ahab(anonymous_client, ahab_pki):
    # The SRK table isn't exposed, so only the SHA-512 digest size is checked
    assert len(get_efuses(anonymous_client, ahab_pki)) == hashlib.sha512().digest_size


def test_efuses_unknown(anonymous_client, hab_pki):
    # Needs a tree created first, otherwise the PKI directory doesn't exist
    # and the server fails with 500, see TODO
    response = anonymous_client.get(f"/imx/efuses/{'0' * 32}")
    assert response.status_code == 404


def test_cst(anonymous_client, tmp_path, hab_pki, payload, signed):
    commands, srk_table, certs, signatures = parse_csf(signed)

    keys = parse_srk_table(srk_table)
    assert len(keys) == 4
    assert srk_efuses(keys) == get_efuses(anonymous_client, hab_pki)

    # Both the CSF and the image key are issued by the SRK in use
    assert sorted(certs) == [1, 2]
    for cert in certs.values():
        assert issued_by(cert, srk_public_key(keys[0]))
        assert not issued_by(cert, srk_public_key(keys[1]))

    (csf_key, csf_blocks, csf_signature), (img_key, img_blocks, img_signature) = signatures
    assert (csf_key, csf_blocks) == (1, [])
    assert verify_cms(tmp_path, certs[1], commands, csf_signature)

    assert (img_key, img_blocks) == (2, [(LOAD_ADDRESS, PAYLOAD_SIZE)])
    assert verify_cms(tmp_path, certs[2], payload, img_signature)
    assert not verify_cms(tmp_path, certs[1], payload, img_signature)

    tampered = bytearray(payload)
    tampered[PAYLOAD_SIZE // 2] ^= 0xff
    assert not verify_cms(tmp_path, certs[2], bytes(tampered), img_signature)


def test_cst_other_pki(client, anonymous_client, hab_pki, payload):
    # The SRK table embedded in the CSF comes from the requested PKI tree
    other = create_pki(client, "hab")
    _, srk_table, _, _ = parse_csf(sign(client, other, payload))
    keys = parse_srk_table(srk_table)
    assert srk_efuses(keys) == get_efuses(anonymous_client, other)
    assert srk_efuses(keys) != get_efuses(anonymous_client, hab_pki)


