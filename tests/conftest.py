import contextlib
import os
import shutil
import socket
import subprocess
import sys
import time

import pytest

from helpers import Client

REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(REPO_DIR, "src")
API_SPEC = os.path.join(REPO_DIR, "api.yml")

STARTUP_TIMEOUT = 30


def required_env(name):
    value = os.environ.get(name)
    if not value:
        pytest.fail(f"`{name}` env var must be set to run the tests")
    return value


def free_port():
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def wait_for_server(proc, host, port, log_path):
    deadline = time.monotonic() + STARTUP_TIMEOUT
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            with open(log_path) as log:
                pytest.fail(f"Server exited during startup:\n{log.read()}")
        try:
            with socket.create_connection((host, port), timeout=1):
                return
        except OSError:
            time.sleep(0.2)
    pytest.fail(f"Server did not start within {STARTUP_TIMEOUT}s, see {log_path}")


