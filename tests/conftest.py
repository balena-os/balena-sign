@contextlib.contextmanager
def run_server(base_dir, fleet_id):
    """
    Runs the server from a fresh copy of the application in base_dir and
    yields its URL.
    """
    # Lay out the application like the Docker image does, so that secrets
    # generated by the tests end up in a throwaway directory.
    app_dir = base_dir / "app"
    home_dir = base_dir / "home"
    shutil.copytree(SRC_DIR, app_dir,
                    ignore=shutil.ignore_patterns("__pycache__", "secrets"))
    shutil.copy(API_SPEC, app_dir)
    (app_dir / "secrets" / "gpg").mkdir(mode=0o700, parents=True)
    (app_dir / "secrets" / "x509").mkdir()
    home_dir.mkdir()

    # The Docker image runs in UTC, which rsa.sign relies on for its timestamp.
    env = dict(os.environ, FLEET_ID=fleet_id, HOME=str(home_dir), TZ="UTC")
    # Only the i.MX tests need CST, they check for it themselves
    cst_dir = os.environ.get("BALENASIGN_TEST_CST_DIR")
    if cst_dir:
        env["CST_DIR"] = cst_dir
        env["PATH"] = os.pathsep.join(
            [os.path.join(cst_dir, "linux64", "bin"), env["PATH"]])
    host = "127.0.0.1"
    port = free_port()
    log_path = base_dir / "server.log"
    with open(log_path, "w") as log:
        proc = subprocess.Popen(
            [sys.executable, "-m", "gunicorn",
             "-k", "uvicorn.workers.UvicornWorker",
             "--chdir", str(app_dir),
             "--workers", "4",
             "--bind", f"{host}:{port}",
             "app:application"],
            env=env, stdout=log, stderr=subprocess.STDOUT)

    try:
        wait_for_server(proc, host, port, log_path)
        yield f"http://{host}:{port}"
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()
        # gpg starts gpg-agent as a daemon, which outlives the server
        subprocess.run(["gpgconf", "--homedir", str(app_dir / "secrets" / "gpg"),
                        "--kill", "all"], capture_output=True, check=False)


